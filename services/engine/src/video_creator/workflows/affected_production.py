MEDIA_TYPES = {"video": "video/mp4", "narration_audio": "audio/wav", "mixed_audio": "audio/wav", "cover": "image/jpeg"}


def require_services(port, lease, services, execution_ports=None):
    from video_creator.workflows.autonomous_production import (
        AutonomousServices,
        CurrentPolicyServices,
    )

    if type(services) is AutonomousServices:
        original = services.execution_ports
    elif type(services) is CurrentPolicyServices:
        original = services.policy_execution_ports
    else:
        raise EngineError("production_services_not_ready", "The original registered runtime must inject its actual same-Run production services.", 503)
    if original is None or execution_ports is not None and original is not execution_ports:
        raise EngineError("production_services_denied", "Actual original human/policy port identity must match the registered runtime object.", 403)
    actual = require_final_port(port)
    if actual.assert_production_services(lease, services, original) is not None:
        raise EngineError("production_services_denied", "Only actual service-held current checks may admit the original source object.", 403)
    return services


def authorize(port, lease, continuation, proposal, services, *, original=None):
    """Recheck the real held source immediately before each bounded effect."""
    from video_creator.application.engine import canonical, digest

    current_attempt().check()
    require_services(port, lease, services)
    actual = require_final_port(port).authorize_affected_execution(lease, continuation, proposal)
    repair = continuation.snapshot.repair
    if type(actual) in RECIPE_EXECUTIONS:
        require_recipe_execution(actual, continuation, proposal)
        if (actual.binding != continuation.binding or actual.execution_fence != lease.fencing_token
                or actual.parent_preparation_id != continuation.snapshot.preparation_id
                or actual.parent_intent_sha256 != continuation.snapshot.preparation_intent_sha256):
            raise EngineError("affected_execution_binding_invalid", "Recipe command must retain the original Run, intent and current fence.", 403)
    elif (type(actual) is not AffectedRepairExecution or repair is None
            or actual.binding != continuation.binding or actual.execution_fence != lease.fencing_token
            or actual.parent_preparation_id != continuation.snapshot.preparation_id
            or actual.parent_intent_sha256 != continuation.snapshot.preparation_intent_sha256
            or actual.source_report_ref != repair.source_report_ref
            or (actual.affected_artifact_ids, actual.failed_unit_ids, actual.requested_action,
                actual.changed_media_roles, actual.affected_shot_ids) != (
                proposal.affected_artifact_ids, proposal.failed_unit_ids, proposal.requested_action,
                proposal.changed_media_roles, proposal.affected_shot_ids)):
        raise EngineError("affected_execution_binding_invalid", "Only the current held command may bind this exact original failed subset and action.", 403)
    if original is not None and _command_facts(actual) != _command_facts(original):
        raise EngineError("affected_execution_changed", "A repair cannot switch its original committed command between effects.", 409)
    # The hash is read from the registered actual command, never generated by
    # this consumer from an unapproved proposal.
    if len(actual.repair_command_sha256) != 64 or digest(canonical(services.engine.get_request(lease))) != actual.binding.request_sha256:
        raise EngineError("affected_execution_binding_invalid", "The original request must remain bound to the actual command.", 409)
    return actual


def _command_facts(value):
    if type(value) in RECIPE_EXECUTIONS:
        return command_facts(value)
    if type(value) is not AffectedRepairExecution:
        raise EngineError("affected_execution_binding_invalid", "The sole actual execution type is required.", 403)
    return (value.binding, value.execution_fence, value.parent_preparation_id, value.parent_intent_sha256,
            value.repair_command_sha256, value.source_report_ref, value.affected_artifact_ids, value.failed_unit_ids,
            value.requested_action, value.changed_media_roles, value.affected_shot_ids)


def proposal_for_failure(readset, continuation, *, bundle, lease, port=None):
    """Finite data from actual failed artifacts/units; this never grants scope."""
    from video_creator.application.engine import canonical, digest
    from video_creator.domain.component_diagnosis import (
        CurrentFinalDiagnosticContinuationV1,
    )
    from video_creator.workflows.bundle_recovery import _documents

    if type(continuation) is CurrentFinalDiagnosticContinuationV1:
        return require_final_port(port).prepare_affected_recipe_proposal(continuation)

    repair, assembly = continuation.snapshot.repair, readset.assembly
    if repair is None or assembly is None or repair.source_report_ref not in readset.preparation.materials:
        raise EngineError("affected_repair_source_invalid", "The actual parent assembly and Ready failed report are required.", 422)
    if repair.allowed_action == "guidance_required":
        raise EngineError("final_evidence_guidance_required", "Actual human guidance has not yet granted a bounded repair action.", 409)
    if not set(repair.affected_artifact_ids) <= {item.artifact_id for item in readset.allocations}:
        raise EngineError("affected_repair_scope_invalid", "Only actual failed parent allocation IDs may be proposed.", 403)
    roles, shot_ids = (), ()
    if repair.allowed_action == "regenerate_affected_media":
        media = {artifact.artifact_id: artifact.roles[0] for artifact in assembly.media_artifacts}
        changed = {media[identity] for identity in repair.affected_artifact_ids if identity in media}
        # Explicit dependency closure only. The held service must independently
        # intersect this proposal with the original approved finite plan/policy.
        if "narration_audio" in changed:
            changed.update(("video", "mixed_audio"))
        if "mixed_audio" in changed:
            changed.add("video")
        if not changed:
            # Report-derived suggestions are deliberately narrower than an
            # all-master retry. They still need the original held service's
            # independent plan/policy/rights intersection; old plans with no
            # explicit finite repair target must remain guidance-required.
            by_check = {"media_integrity": ("video",), "semantic_sources": ("video",),
                        "actual_transcript": ("narration_audio", "mixed_audio", "video"),
                        "audio_timeline": ("mixed_audio", "video")}
            changed.update(by_check.get(repair.failed_check_code, ()))
            if not changed:
                raise EngineError("affected_repair_plan_projection_missing", "This actual failed check has no supported finite media proposal; current approved target guidance is required.", 409)
        roles = tuple(role for role in MEDIA_TYPES if role in changed)
        if "video" in changed and "narration_audio" not in changed and "mixed_audio" not in changed:
            _, _, _, parsed = _documents(readset)
            transcript = parsed["transcript"]
            units = {unit.unit_id: unit.transcript_unit_id for unit in transcript.alignment.boundaries}
            actual_units = {utterance.utterance_id for utterance in transcript.transcript.utterances}
            selected_units = {units.get(identity, identity) for identity in repair.failed_unit_ids}
            if not selected_units or not selected_units <= actual_units:
                raise EngineError("affected_repair_units_invalid", "Actual failed speech units are required; unknown units cannot expand to every shot.", 422)
            shot_refs = {shot for segment in parsed["segments"] if set(segment.transcript_unit_refs) & selected_units
                         for shot in segment.shot_revision_ids}
            source = next((ref for ref in assembly.creative_revision_refs if ref.kind == "storyboard"), None)
            original = next((value for value in bundle.creative_revisions(lease) if source is not None and value.revision_id == source.revision_id), None)
            if original is None or digest(canonical(original)) != source.content_sha256:
                raise EngineError("affected_creative_source_invalid", "The actual original storyboard source is required.", 409)
            shot_ids = tuple(item["shot_id"] for item in original.body["shots"] if item["shot_revision_id"] in shot_refs)
            if not shot_ids:
                raise EngineError("affected_repair_units_invalid", "Failed units must resolve to an actual bounded shot subset.", 422)
    return AffectedRepairProposal(format="current-affected-repair-proposal-v1", parent_preparation_id=readset.preparation.preparation_id,
                affected_artifact_ids=repair.affected_artifact_ids, failed_unit_ids=repair.failed_unit_ids,
                requested_action=repair.allowed_action, changed_media_roles=roles, affected_shot_ids=shot_ids)


def read_affected(port, lease, continuation, execution):
    current_attempt().check()
    value = require_final_port(port).read_affected_execution_inputs(lease, continuation)
    if type(value) not in {AffectedRepairReadSet, AffectedRepairReadSetV2}:
        raise EngineError("affected_recovery_invalid", "Only the original held repair read set is accepted.", 503)
    if _command_facts(value.execution) != _command_facts(execution):
        raise EngineError("affected_recovery_invalid", "Recovery must retain every original command field and current fence.", 409)
    if (value.parent.binding != execution.binding or value.parent.execution_fence != lease.fencing_token
            or value.parent.preparation.preparation_id != execution.parent_preparation_id):
        raise EngineError("affected_recovery_invalid", "The actual original parent must belong to the same registered Run.", 409)
    if value.masters is not None:
        require_observation(value.masters, execution)
    if value.child is not None and (value.child.binding != execution.binding or value.child.execution_fence != lease.fencing_token
            or value.child.preparation.preparation_id == execution.parent_preparation_id
            or execution.requested_action == "regenerate_affected_media" and value.masters is None):
        raise EngineError("affected_recovery_invalid", "An actual committed child must retain its original observed changed masters and parent.", 409)
    return value


def require_observation(value, execution):
    key, input_sha, _ = _step(execution, "master")
    if (type(value) is not AffectedMasterObservation or value.binding != execution.binding
            or value.parent_preparation_id != execution.parent_preparation_id
            or value.repair_command_sha256 != execution.repair_command_sha256
            or (value.step_key, value.step_input_sha256) != (key, input_sha)
            or value.changed_media_roles != execution.changed_media_roles
            or set(value.effective_media_roles) != set(MEDIA_TYPES)
            or len(set(value.effective_media_roles.values())) != 4 or not value.operation_ids):
        raise EngineError("affected_master_observation_invalid", "The held result must preserve the exact changed role subset and complete effective master mapping.", 409)
    return value


def regenerate_masters(port, lease, continuation, proposal, services, parent):
    """Original builders/Worker/ledger only; restores observed masters first."""
    from video_creator.application.engine import canonical, digest
    from video_creator.workflows.autonomous_production import (
        MASTER_INDEX_DESTINATION,
        _step_result,
    )

    execution = authorize(port, lease, continuation, proposal, services)
    if execution.requested_action != "regenerate_affected_media":
        raise EngineError("affected_execution_action_invalid", "Generation only consumes an actual authorized regeneration command.", 403)
    recovered = read_affected(port, lease, continuation, execution)
    if recovered.masters is not None:
        return execution, recovered.masters
    if recovered.child is not None:
        raise EngineError("affected_recovery_invalid", "Child state cannot precede actual masters.", 409)
    parent = recovered.parent
    assembly = parent.assembly
    if assembly is None:
        raise EngineError("final_assembly_unavailable", "The original authored parent is required before generation.", 503)
    revisions = {value.revision_id: value for value in services.bundle.creative_revisions(lease)}
    original = {}
    for ref in assembly.creative_revision_refs:
        value = revisions.get(ref.revision_id)
        if value is None or digest(canonical(value)) != ref.content_sha256 or value.kind != ref.kind:
            raise EngineError("affected_creative_source_invalid", "Actual original approved creative bytes cannot be replaced by current guidance.", 409)
        original[ref.kind] = value
    plan = c.CreativeProposal.model_validate(original["plan"].body["proposal"])
    recipe = recipe_for_command(execution, original["plan"].body) if type(execution) in RECIPE_EXECUTIONS else None
    shots = {shot.shot_id: shot for shot in plan.shots}
    regenerated = execution.regenerated_shot_ids if recipe is not None else execution.affected_shot_ids
    changed = set(execution.changed_media_roles)
    if (not set(regenerated) <= set(shots)
            or regenerated and "video" not in changed
            or "narration_audio" in changed and not {"video", "mixed_audio"} <= changed
            or "mixed_audio" in changed and "video" not in changed):
        raise EngineError("affected_execution_scope_invalid", "Changed roles retain actual clip/audio dependencies without an all-master fallback.", 403)
    effective = {value.roles[0]: value.asset_id for value in assembly.media_artifacts}
    if set(effective) != set(MEDIA_TYPES):
        raise EngineError("affected_master_source_invalid", "All four real parent roles are required.", 422)
    generated, source_steps = {}, []
    guard = lambda: authorize(port, lease, continuation, proposal, services, original=execution)
    if "narration_audio" in changed:
        generated.update(_generated(services, lease, execution, "narration", (("narration_audio", "audio/wav"),),
                        original["script"].body, services.narration_route_id, services.narration_driver, guard, master_roles=True))
        source_steps.append(_step(execution, "narration")[0])
    clips = []
    if "video" in changed and (recipe is None or recipe.recipe_id != "cover-from-preserved-video-v1"):
        retained = (preserved_clips(port, lease, continuation, execution, services,
                    tuple(shot for shot in plan.shots if shot.shot_id not in regenerated)) if recipe is not None else {})
        for shot in plan.shots:
            if shot.shot_id in regenerated:
                clip = _generated(services, lease, execution, "picture", ((shot.shot_id, "video/mp4"),),
                            shot.model_dump(mode="json"), services.picture_route_id, services.picture_driver, guard, shot_id=shot.shot_id)
                source_steps.append(_step(execution, "picture", shot_id=shot.shot_id)[0])
            elif recipe is not None:
                clip = {shot.shot_id: retained[shot.shot_id]}
            else:
                guard()
                saved = _step_result(services.engine.read_step(lease, "production-" + shot.shot_id))
                if saved is None:
                    raise EngineError("affected_clip_source_unavailable", "An unaffected shot must reuse its actual original successful source Step.", 409)
                clip = _registered_outputs(services, lease, saved, ((shot.shot_id, "video/mp4"),), master_roles=False)
            clips.append(clip[shot.shot_id])
    edit_roles = tuple((role, MEDIA_TYPES[role]) for role in ("video", "mixed_audio", "cover") if role in changed)
    if edit_roles:
        data = {"clips": clips, "storyboard": original["storyboard"].body,
                "narration_audio": generated.get("narration_audio", effective["narration_audio"]),
                "preserved_mixed_audio": effective["mixed_audio"], "preserved_video": effective["video"],
                "changed_media_roles": [role for role, _ in edit_roles]}
        if recipe is not None:
            data.update(recipe_id=recipe.recipe_id, regenerated_shot_ids=list(regenerated),
                        impacted_shot_ids=list(execution.impacted_shot_ids), changed_master_roles=list(execution.changed_media_roles))
        generated.update(_generated(services, lease, execution, "edit", edit_roles, data, services.edit_route_id,
                        services.edit_driver, guard, master_roles=True))
        source_steps.append(_step(execution, "edit")[0])
    if set(generated) != changed or any(generated[role] == effective[role] for role in generated):
        raise EngineError("affected_master_source_invalid", "Every changed role must be its actual new independently registered output.", 409)
    key, input_sha, dedupe = _step(execution, "master")
    guard()
    services.engine.begin_step(lease, key, input_sha)
    route = services.engine.configured_route(services.master_index_route_id)
    if (route.destination != MASTER_INDEX_DESTINATION or route.source != "owned_local" or route.capability != "video"
            or route.credential_ref or route.max_operation_cost.units()):
        raise EngineError("production_master_index_denied", "Affected master indexing retains the original credential-free local route.", 403)

    def validate(permit, secret):
        guard()
        if (secret is not None or permit.route != route or (permit.run_id, permit.fencing_token) != (lease.run_id, lease.fencing_token)):
            raise EngineError("affected_master_permit_invalid", "Actual local permit must retain the same original route, Run and fence.", 403)
        observed = {}
        for role, asset_id in generated.items():
            guard()
            asset = services.bundle.asset(lease, asset_id)
            path = services.bundle.content_path(lease, asset_id)
            probe = services.media_validator(path, MEDIA_TYPES[role])
            if asset.media_type != MEDIA_TYPES[role] or not probe.decoded or probe != asset.probe:
                raise EngineError("affected_master_decode_invalid", "Every changed master retains its actual complete decoded source evidence.", 422)
            observed[role] = {"asset_id": asset.asset_id, "sha256": asset.sha256, "probe": probe.model_dump(mode="json")}
        resulting = {**effective, **generated}
        video = services.bundle.asset(lease, resulting["video"])
        mixed = services.bundle.asset(lease, resulting["mixed_audio"])
        if video.probe.duration_us != mixed.probe.duration_us:
            raise EngineError("affected_master_timeline_invalid", "New and preserved effective masters must retain the same actual full work duration.", 422)
        return c.OperationObservation(status="succeeded", actual_cost=c.Money(amount="0"), cost_evidence="confirmed_no_charge",
                    result_json={"observed_masters": observed, "scope": "changed real registered masters only; preserved parent roles are not regenerated"})

    observation = services.executor.execute(lease, c.OperationIntent(step_key=key, input_sha256=input_sha,
                dedupe_key=dedupe, route_id=services.master_index_route_id, reserved_cost=c.Money(amount="0")), validate)
    if observation.status != "succeeded":
        raise EngineError("affected_master_unresolved", "Original master operation remains unresolved; never submit another command.", 409,
                    "reconcile" if observation.status in {"unknown", "pending"} else "never")
    guard()
    services.engine.complete_step(lease, key, asset_ids=tuple(generated.values()),
                result_json={"media_roles": generated, "source_steps": source_steps})
    current_attempt().check()
    return execution, require_observation(require_final_port(port).observe_affected_masters(lease, execution, step_key=key), execution)


def _registered_outputs(services, lease, saved, roles, *, master_roles):
    ids = saved.get("asset_ids")
    names = [role for role, _ in roles]
    if (type(ids) is not list or len(ids) != len(roles) or len(set(ids)) != len(ids)
            or any(type(value) is not str for value in ids) or saved["result"].get("roles") != names):
        raise EngineError("affected_output_step_invalid", "Saved source Step retains its complete original ordered output identities.", 409)
    result = dict(zip(names, ids, strict=True))
    if master_roles and saved["result"].get("media_roles") != result:
        raise EngineError("affected_output_step_invalid", "Only the backend's fenced registered role mapping is accepted.", 409, "reconcile")
    for identity, (_, media_type) in zip(ids, roles, strict=True):
        asset = services.bundle.asset(lease, identity)
        if asset.media_type != media_type:
            raise EngineError("affected_output_step_invalid", "Registered output role and actual media type must agree.", 422)
    return result


def _generated(services, lease, execution, stage, roles, data, route_id, builder, guard, *, shot_id=None, master_roles=False):
    from video_creator.application.engine import canonical, digest
    from video_creator.workflows.autonomous_production import (
        BoundProductionDriver,
        _step_result,
    )

    key, input_sha, dedupe = _step(execution, stage, shot_id=shot_id)
    guard()
    saved = _step_result(services.engine.begin_step(lease, key, input_sha))
    if saved is not None:
        return _registered_outputs(services, lease, saved, roles, master_roles=master_roles)
    route = services.engine.configured_route(route_id)
    outputs = tuple(services.worker.allocate_output(lease, key, input_sha, role, media_type,
                    "affected-production-v1:" + stage, "Only the actual current bounded command and final rights checks admit these outputs")
                    for role, media_type in roles)
    spec = builder(data, outputs, ordinary_lease=lease, cancel=current_attempt().cancel_requested,
                    deadline_monotonic=current_attempt().deadline_monotonic)
    if type(spec) is not BoundProductionDriver or not callable(spec.invoke):
        raise EngineError("affected_driver_missing", "Only the original installed bounded production driver is executable.", 503)
    guard()
    observation = services.executor.execute(lease, c.OperationIntent(step_key=key, input_sha256=input_sha,
                    dedupe_key=dedupe, route_id=route_id, reserved_cost=route.max_operation_cost), spec.invoke, request_payload=spec.request_payload)
    if observation.status != "succeeded" or type(observation.result_json) is not dict:
        raise EngineError("affected_operation_unresolved", "The original provider outcome cannot be retried under another input or command.", 409,
                    "reconcile" if observation.status in {"unknown", "pending"} else "never")
    files = tuple(GeneratedFileManifest.model_validate(item) for item in observation.result_json.get("generated_files", ()))
    if tuple(file.attempt_id for file in files) != tuple(output.attempt_id for output in outputs):
        raise EngineError("affected_output_manifest_invalid", "Actual successful observation must include every original ordered output reservation.", 409, "reconcile")
    result = {"roles": [role for role, _ in roles], "provider_observation_sha256": digest(canonical(observation))}
    guard()
    if master_roles:
        attempts = {role: output.attempt_id for (role, _), output in zip(roles, outputs, strict=True)}
        committed = services.worker.commit_generated_media_step(lease, key, input_sha, files, attempts, result, services.media_validator)
    else:
        committed = services.worker.commit_generated_step(lease, key, input_sha, files, result, services.media_validator)
    saved = _step_result(committed)
    if saved is None:
        raise EngineError("affected_output_commit_invalid", "Only the actual final fenced source Step can supply a master.", 409, "reconcile")
    return _registered_outputs(services, lease, saved, roles, master_roles=master_roles)


def _step(execution, stage, *, shot_id=None):
    return (recipe_step(execution, stage, shot_id=shot_id) if type(execution) in RECIPE_EXECUTIONS
            else affected_master_step(execution, stage, shot_id=shot_id))
